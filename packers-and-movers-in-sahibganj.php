    <!-- FAQ Accordion Interactive Script -->
    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const faqItems = document.querySelectorAll('.custom-faq-item');
            faqItems.forEach(item => {
                const button = item.querySelector('.faq-quest-btn');
                const answer = item.querySelector('.faq-ans-box');
                
                // Hide answers by default except first one
                answer.style.display = 'none';

                button.addEventListener('click', () => {
                    const isOpen = answer.style.display === 'block';
                    
                    // Close all
                    faqItems.forEach(i => {
                        i.querySelector('.faq-ans-box').style.display = 'none';
                        const icon = i.querySelector('.faq-quest-btn i');
                        if (icon) icon.style.transform = 'rotate(0deg)';
                    });

                    // Toggle current
                    if (!isOpen) {
                        answer.style.display = 'block';
                        const currentIcon = button.querySelector('i');
                        if (currentIcon) currentIcon.style.transform = 'rotate(180deg)';
                    }
                });
            });
            // Open first FAQ by default
            if (faqItems.length > 0) {
                faqItems[0].querySelector('.faq-ans-box').style.display = 'block';
                const firstIcon = faqItems[0].querySelector('.faq-quest-btn i');
                if (firstIcon) firstIcon.style.transform = 'rotate(180deg)';
            }
        });
    </script>
</body>
