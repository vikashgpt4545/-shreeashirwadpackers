        $slug = trim($path, '/');
        if (strpos($slug, 'packers-and-movers-in-') === 0) {
            return substr($slug, strlen('packers-and-movers-in-'));
        }
    }
    
    // Check request uri
    $uri = parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH);
    $slug = trim($uri, '/');
    if (strpos($slug, 'packers-and-movers-in-') === 0) {
        return substr($slug, strlen('packers-and-movers-in-'));
    }
    
    return null;
}

/**
 * Get cluster context for a given slug
 */
function get_location_cluster_context($slug = null) {
    global $jharkhand_district_clusters;
    if ($slug === null) {
        $slug = get_current_location_slug();
    }
    if (!$slug) {
        return null;
    }
    
    // Is it a District Hub?
    if (isset($jharkhand_district_clusters[$slug])) {
        return [
            'type' => 'HEAD',
            'district_slug' => $slug,
            'district_name' => $jharkhand_district_clusters[$slug]['name'],
            'district_url' => $jharkhand_district_clusters[$slug]['url'],
            'children' => $jharkhand_district_clusters[$slug]['children'],
            'self' => $slug
        ];
    }
    
    // Is it a child sub-division?
    foreach ($jharkhand_district_clusters as $d_slug => $d_info) {
        if (isset($d_info['children'][$slug])) {
            return [
                'type' => 'CHILD',
                'district_slug' => $d_slug,
                'district_name' => $d_info['name'],
                'district_url' => $d_info['url'],
                'children' => $d_info['children'],
                'self_name' => $d_info['children'][$slug]['name'],
                'self' => $slug
            ];
        }
    }
    
    return null;
}

