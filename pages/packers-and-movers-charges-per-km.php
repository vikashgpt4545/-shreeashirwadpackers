function calculateKmCost(e) {
    e.preventDefault();
    var vType = document.getElementById('pkmVehicle').value;
    var mType = document.getElementById('pkmType').value;
    var dist = parseInt(document.getElementById('pkmDistance').value, 10);

    var baseLabor = 2800;
    var baseRatePerKm = 24;
    var tollEst = 0;

    if (vType === 'ace') {
        baseLabor = 2000; baseRatePerKm = 18;
    } else if (vType === 'pickup') {
        baseLabor = 2800; baseRatePerKm = 22;
    } else if (vType === 'canter17') {
        baseLabor = 3800; baseRatePerKm = 28;
    } else if (vType === 'container19') {
        baseLabor = 4800; baseRatePerKm = 34;
    } else if (vType === 'trailer') {
        baseLabor = 7500; baseRatePerKm = 48;
    }

    if (dist <= 30) {
        baseRatePerKm = Math.round(baseRatePerKm * 2.2);
    } else if (dist <= 150) {
        baseRatePerKm = Math.round(baseRatePerKm * 1.4);
    } else if (dist <= 500) {
        baseRatePerKm = Math.round(baseRatePerKm * 1.1);
    } else if (dist >= 1200) {
        baseRatePerKm = Math.round(baseRatePerKm * 0.85);
    }

    var freight = dist * baseRatePerKm;

    if (dist > 50) {
        tollEst = Math.round(dist * 3.5);
    }

    var minTotal = baseLabor + freight + tollEst;
    var maxTotal = Math.round(minTotal * 1.2);
    var effectivePerKm = Math.round(minTotal / dist);

    document.getElementById('pkmRatePerKm').innerText = '₹' + effectivePerKm + ' / km';
    document.getElementById('pkmFreightCost').innerText = '₹' + freight.toLocaleString('en-IN');
    document.getElementById('pkmLaborCost').innerText = '₹' + baseLabor.toLocaleString('en-IN');
    document.getElementById('pkmTollCost').innerText = '₹' + tollEst.toLocaleString('en-IN');
    document.getElementById('pkmTotalRange').innerText = '₹' + minTotal.toLocaleString('en-IN') + ' - ₹' + maxTotal.toLocaleString('en-IN');

    var resBox = document.getElementById('pkmResultBox');
    resBox.style.display = 'block';
    resBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}
