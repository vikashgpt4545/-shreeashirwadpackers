        <!-- Section 6: FAQs -->
        <h2 class="pmgst-section-heading">Frequently Asked Questions: Packers and Movers GST Rates</h2>
        <div class="pmgst-faq-item">
            <h3>What is the exact GST rate on packers and movers services in India?</h3>
            <p>The GST rate on packers and movers depends on the service scope. For a complete end-to-end relocation service (which includes packing, loading, road transport, unloading, and unpacking), it is treated as a composite supply under SAC code 9987 and attracts 18% GST (9% CGST + 9% SGST for intrastate, or 18% IGST for interstate). If you hire only transportation/freight without packing or labor (pure Goods Transport Agency - GTA service), the GST rate is 5% under SAC code 9965 (without Input Tax Credit).</p>
        </div>
        <div class="pmgst-faq-item">
            <h3>Can businesses claim Input Tax Credit (ITC) on packers and movers GST bills?</h3>
            <p>Yes, registered businesses and corporate enterprises can claim full Input Tax Credit (ITC) on the 18% GST charged on commercial office shifting, server transfers, factory warehouse relocations, and corporate employee transfers where the relocation contract and invoice are billed directly in the company's GSTIN name.</p>
        </div>
        <div class="pmgst-faq-item">
            <h3>What are the official SAC codes for packers and movers services?</h3>
            <p>The primary SAC (Services Accounting Code) for complete packers and movers services is SAC 9987 (Cargo handling, packaging, and composite support services). For pure transport vehicle hiring (GTA freight service), the code is SAC 9965 (Goods transport services by road). Transit insurance is classified under SAC 9971 (Freight and marine insurance services, taxed at 18%).</p>
        </div>
        <div class="pmgst-faq-item">
            <h3>Does Reverse Charge Mechanism (RCM) apply to packers and movers services?</h3>
            <p>Reverse Charge Mechanism (RCM) applies specifically to pure Goods Transport Agency (GTA) freight services taxed at 5% when availed by specified registered entities (such as factories, registered companies, or partnerships). However, when a relocation company provides a full turnkey package (packing, loading, transport, and unloading as a composite supply taxed at 18%), Forward Charge Mechanism applies, meaning the moving company collects and remits the 18% GST.</p>
        </div>
        <div class="pmgst-faq-item">
            <h3>What mandatory details must be present on a valid GST moving bill?</h3>
            <p>A valid GST moving invoice must include the moving company's legal name, registered address, and active 15-digit GSTIN; consecutive tax invoice serial number and date; consignor and consignee details with addresses and GSTIN (if corporate); specific SAC code (9987 or 9965); itemized breakdown of freight, packing material, labor, and insurance; tax rates (CGST/SGST or IGST); and vehicle registration/LR Bilty number.</p>
        </div>
        <div class="pmgst-faq-item">
            <h3>How can I verify if a moving company's GST number is authentic or fake?</h3>
            <p>You can verify any moving operator's GSTIN for free on the official government GST portal (services.gst.gov.in/services/searchtp). Enter the 15-digit GSTIN printed on their quotation or invoice to confirm that the legal business name matches the operator, the registration status is 'Active', and the registered principal place of business is genuine.</p>
        </div>

