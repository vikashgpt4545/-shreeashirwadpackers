  <h2>Step-by-Step Industrial Machinery Shifting Process</h2>
  <p>Industrial relocations require military-grade engineering precision. Here is how our certified rigging team executes every phase of the project:</p>

  <h3>Phase 1: Engineering Site Survey & Structural Assessment</h3>
  <p>Our Rigging Project Engineer visits your factory to inspect machine dimensions, exact weight, Center of Gravity (CoG), foundation anchoring bolts, ceiling hook clearances, and floor load-bearing limits. We map the exit pathway from the machine foundation to the factory loading bay, noting any narrow doorways or overhead duct obstructions.</p>

  <h3>Phase 2: De-Anchoring & Machine Preparation</h3>
  <p>Client engineers disconnect electrical mains, pneumatic hoses, and hydraulic fluid circuits. Our team removes hold-down foundation anchor nuts, cleans the machine perimeter, locks all counterweights and moving axes with transport locking fixtures, and wraps critical guideways with anti-corrosion VCI film.</p>

  <h3>Phase 3: Hydraulic Toe-Jacking & Skating Out</h3>
  <p>Using calibrated low-clearance hydraulic toe jacks, our riggers incrementally elevate the machine base millimeter by millimeter, placing hardwood dunnage blocks at every stage. Heavy-duty 360-degree rotating machinery skates are slid beneath the machine footings. The machine is carefully rolled along the factory floor by controlled mechanical pullers.</p>

  <h3>Phase 4: Crane Lifting & Trailer Rigging</h3>
  <p>At the loading bay, a certified hydraulic mobile crane lifts the machine using designated lifting lugs and soft web slings to prevent structural deflection. The machine is lowered onto a low-bed trailer, rested on shock-absorbing timber sleepers, and lashed securely using high-tensile ratchet chain binders and corner edge buffers.</p>

  <h3>Phase 5: Secure Transport & E-Way Bill Compliance</h3>
  <p>Our trailer navigates the approved route under escort if over-dimensional cargo (ODC) clearances are required. We handle all mandatory GST E-Way bill generation, state road permits, and police transit clearances.</p>

  <h3>Phase 6: Unloading, Foundation Positioning & Precision Leveling</h3>
  <p>At the destination factory, the crane or forklift lifts the machine off the trailer, skates it into the new shop floor bay, aligns it precisely over newly drilled foundation bolts, and lowers it onto isolation pads. Using precision spirit levels, we verify horizontal and vertical alignment before handover to your commissioning team.</p>

