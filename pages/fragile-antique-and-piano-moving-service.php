        <h2 class="faps-section-heading">Frequently Asked Questions: Fragile Antique &amp; Piano Moving</h2>
        <div class="faps-faq-item">
            <h3>Why shouldn't general packers and movers move an acoustic piano?</h3>
            <p>An acoustic piano is both a heavy piece of furniture (weighing 200 kg to over 500 kg) and a precision musical instrument under 18 to 20 tons of internal string tension on a cast iron harp. Standard moving labor often tilts pianos by the delicate wooden legs or lyre pedals, leading to fractured leg dowels, cracked pinblocks, or soundboard splinters. We use heavy-duty padded piano skid boards, locking harnesses, and specialized piano dollies that isolate structural frame tension entirely.</p>
        </div>
        <div class="faps-faq-item">
            <h3>How do you protect heavy hand-carved white marble mandirs during transit?</h3>
            <p>Makrana and Italian marble temples contain natural stone cleavage planes that can fracture under sudden road shocks. We dismantle removable dome spires (shikhars), pillars, and Murtis individually. Each stone element is wrapped in non-abrasive foam sheets, corner protected with high-density EVA foam, and secured inside a customized, heat-treated pine wood skeleton crate with internal bracing that eliminates any internal shifting.</p>
        </div>
        <div class="faps-faq-item">
            <h3>What is custom wooden crating, and is it built on-site?</h3>
            <p>Custom wooden crating involves constructing tailored pine wood or commercial ply enclosures engineered to the exact millimeter dimensions of your high-value asset. Our carpenters measure the item on-site, build the internal shock-absorbing foam cushioning bed, fabricate the rigid external wooden cage, and screw-seal the crate for structural rigidity and easy destination unboxing.</p>
        </div>
        <div class="faps-faq-item">
            <h3>How are delicate glass crystal chandeliers and large framed paintings transported?</h3>
            <p>For crystal chandeliers, delicate crystal drops and arms are individually wrapped in tissue paper and bubble wrap, with the core frame suspended inside a custom vertical wooden crate so no pressure rests on fragile joints. Large oil paintings and Tanjore art are wrapped in acid-free glassine paper, corner-capped, and placed in specialized telescoping picture boxes or wooden shadow crates.</p>
        </div>
        <div class="faps-faq-item">
            <h3>Will my acoustic piano require re-tuning after the relocation?</h3>
            <p>Yes, all acoustic upright and grand pianos require tuning after relocation. Even with shock-mitigated air-ride transportation, shifting between different geographic elevations, atmospheric humidity levels, and temperature zones causes the soundboard wood to expand or contract slightly. We recommend allowing the piano to acclimate to your new home's climate for 2 to 3 weeks before scheduling a piano technician for fine tuning.</p>
