            <p>Yes, by law and safety regulations, the petrol tank must be almost completely emptied (leaving less than 0.5 liters to ride to the nearest petrol pump upon delivery). Transporting a full fuel tank inside an enclosed vehicle presents an extreme vapor flammability hazard on highways. Our pickup team can assist in safely draining excess fuel into your containers before loading.</p>
