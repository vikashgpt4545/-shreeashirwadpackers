            SAIL BSL Quarter Surrender &amp; Clearance Protocol
          </h2>
          <p>
            If you or a family member is retiring from Bokaro Steel Plant, taking voluntary retirement, or transferring to another SAIL unit (such as Bhilai, Rourkela, Durgapur, or IISCO Burnpur), vacating a company quarter involves official administrative clearances. Failure to complete these steps can freeze terminal gratuity or pension dues.
          </p>
          <p>
            <strong>The Step-by-Step Quarter Clearance Process:</strong>
          </p>
          <ol style="padding-left: 20px; margin-bottom: 20px;">
            <li style="margin-bottom: 10px;">
              <strong>Formal Intimation to Town Administration (TA):</strong> Submit an official intimation letter to the Town Administration Department at Sector 4 City Centre at least 15 days prior to your target moving date.
            </li>
            <li style="margin-bottom: 10px;">
              <strong>Electrical Meter Inspection:</strong> Schedule an appointment with the Township Electrical Maintenance wing. An inspector reads the meter, inspects the breaker box, verifies that no unauthorized fittings exist, and issues a Final Meter Reading Slip.
            </li>
            <li style="margin-bottom: 10px;">
              <strong>Civil &amp; Sanitary Fixtures Audit:</strong> A junior civil engineer visits the quarter to inspect doors, windows, sanitary fittings, and structural walls. Any company fittings removed must be restored, or nominal depreciation charges must be acknowledged.
            </li>
            <li style="margin-bottom: 10px;">
              <strong>Dues Clearance &amp; Final Surrender Slip:</strong> Clear all pending electricity, water, and township maintenance dues at the TA cash counters. Obtain the stamped Quarter Vacating Slip (Surrender Certificate).
            </li>
            <li style="margin-bottom: 10px;">
              <strong>Security Gate Passes for Moving Trucks:</strong> Present your moving truck's registration number and driver credentials to the sector security post if required, ensuring uninterrupted loading on moving day.
            </li>
          </ol>
