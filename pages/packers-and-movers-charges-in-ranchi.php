  <h2>Component-by-Component Cost Breakdown: What You Actually Pay For</h2>
  <p>To eliminate ambiguity, let us examine the specific cost heads that comprise an authentic, professional moving estimate in Ranchi. Understanding these individual line items prevents unscrupulous vendors from inflating generalized lumped-sum figures.</p>

  <div class="info-card-grid">
    <div class="info-card">
      <h4>📦 1. Packing Materials Cost</h4>
      <p>High-grade defensive materials guarantee zero transit damage. This includes double-wall heavy-duty 5-ply cartons (₹60 - ₹95 per box), air-bubble wrap rolls (₹800 - ₹1,400 per 100m roll), expanded EPE foam sheets (₹15 - ₹25 per meter), industrial stretch film (₹350 - ₹550 per roll), adhesive packing tape, and customized wooden crating for delicate glass, fine art, or marble tables (₹1,500 - ₹3,500 per crate).</p>
    </div>

    <div class="info-card">
      <h4>👷 2. Skilled Labor & Handling Charges</h4>
      <p>Specialized moving labor requires seasoned skill, not casual daily-wage coolies. Crew charges in Ranchi average ₹650 to ₹900 per skilled packer/handler per day. This fee covers meticulous disassembling of double beds and wardrobe modular units, careful bubble-wrapping, balance-stabilized staircase descending, container floor strapping, and reassembly at destination.</p>
    </div>

    <div class="info-card">
      <h4>🚚 3. Vehicle Freight & Logistics</h4>
      <p>The choice of transport vehicle directly affects cost. Compact 1 RK or bachelor transfers utilize a Tata Ace or Mahindra Bolero Maxi Truck (₹1,500 - ₹2,500 local base fare). Mid-size 2 BHK apartments require a 14-foot closed container truck (₹3,000 - ₹4,800 local base fare). Large 3-4 BHK homes necessitate a 17-foot or 19-foot all-weather weather-sealed container (₹4,500 - ₹7,500 local base fare).</p>
    </div>

    <div class="info-card">
      <h4>🛡️ 4. Transit Insurance Coverage</h4>
      <p>Goods in transit face unforeseen risks on national highways. Authentic moving companies calculate insurance premiums at 1.5% to 3% of your declared asset value. For instance, declaring household contents valued at ₹5,00,000 incurs a nominal transit insurance premium of approximately ₹7,500 to ₹10,000, safeguarding you against total road accidents, vehicle roll-overs, or fire emergencies.</p>
    </div>

    <div class="info-card">
      <h4>📑 5. Goods and Services Tax (GST)</h4>
      <p>In accordance with Indian tax statutes, GTA transport attracts 5% GST (Reverse Charge / Freight Only), whereas complete composite relocation packages (packing, labor, freight, and doorstep unpacking) attract 18% GST. Corporate, defense, and PSU employees need an 18% GST invoice containing company GSTIN to claim 100% employer reimbursement.</p>
    </div>

    <div class="info-card">
      <h4>🏢 6. Floor Elevation & Long Carry Surcharges</h4>
      <p>If either property lacks an operational freight elevator, moving teams must navigate narrow spiral staircases. Standard industry tariffs permit a nominal surcharge of ₹250 to ₹500 per additional floor above the 2nd floor. Similarly, if security rules prevent the truck from parking within 50 meters of the building entrance, a long-carry handling fee (₹300 - ₹700) applies.</p>
